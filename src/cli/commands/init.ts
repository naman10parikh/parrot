/**
 * `parrot init` — wire next-intl into a Next.js App-Router app correctly the FIRST time (JTBD-1; PLAN §4).
 * The footguns the brain names are dodged by construction:
 *   - P2/S2: the routing file is `src/proxy.ts` on Next 16+, `src/middleware.ts` before — VERSION-DETECTED.
 *   - P1/S1: `setRequestLocale(locale)` is codegen'd into the generated `[locale]/layout.tsx` (and any page we
 *            generate), after `await params`, before any translation read.
 *   - P3:    `[locale]` params are `await`ed (Next 15+ made them a Promise).
 *   - JTBD-1.5: `localePrefix` is set DELIBERATELY (default "as-needed"), not left implicit.
 *   - O24/P28: the layout sets `<html lang dir>` so RTL locales render correctly (the font/dir bridge).
 *
 * IDEMPOTENT + NON-DESTRUCTIVE (Q12 / Karpathy surgical): every file is written only if absent; we NEVER
 * rewrite the user's existing pages. Re-running init on an already-wired app is a no-op (reports "skipped").
 */

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { readJsonSafe } from "../util/fs-walk.js";

export type I18nLib = "next-intl" | "i18next";

export interface InitResult {
  readonly dir: string;
  readonly lib: I18nLib;
  readonly nextVersion: number | null;
  /** The routing/middleware file chosen by version detection (`src/proxy.ts` or `src/middleware.ts`). */
  readonly middlewareFile: string;
  /** Files actually written this run (relative to appDir). */
  readonly filesWritten: string[];
  /** Files that already existed and were left untouched (idempotent / non-destructive). */
  readonly filesSkipped: string[];
  readonly defaultLocale: string;
  readonly locales: string[];
}

/** Read the target app's Next.js major version. null if not found (we then assume Next 16 — current default). */
function detectNextMajor(appDir: string): number | null {
  const pkg = readJsonSafe(join(appDir, "package.json"));
  if (!pkg.ok || typeof pkg.value !== "object" || pkg.value === null) return null;
  const deps = {
    ...((pkg.value as Record<string, unknown>)["dependencies"] as Record<string, string> | undefined),
    ...((pkg.value as Record<string, unknown>)["devDependencies"] as Record<string, string> | undefined),
  };
  const spec = deps["next"];
  if (!spec) return null;
  const m = spec.match(/(\d+)/);
  return m ? Number(m[1]) : null;
}

/** Write a file only if it does not exist; record which bucket it fell into. Creates parent dirs. */
function writeIfAbsent(appDir: string, relPath: string, content: string, written: string[], skipped: string[]): void {
  const full = join(appDir, relPath);
  if (existsSync(full)) {
    skipped.push(relPath);
    return;
  }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, content, "utf8");
  written.push(relative(appDir, full));
}

// ---- next-intl codegen templates (the 4 load-bearing files + a seed page) ----

function routingTs(locales: string[], defaultLocale: string): string {
  return `// Generated by parrot — next-intl routing. localePrefix is set DELIBERATELY (JTBD-1.5).
import { defineRouting } from "next-intl/routing";

export const routing = defineRouting({
  locales: ${JSON.stringify(locales)},
  defaultLocale: ${JSON.stringify(defaultLocale)},
  // "as-needed" omits the prefix for the default locale. Choose deliberately:
  //   "always"    — every locale prefixed (/en, /pl, /ar) — clearest for SEO.
  //   "as-needed" — default locale unprefixed (/, /pl, /ar).
  //   "never"     — cookie-only, no URL prefix (multi-tenant SaaS, S9).
  localePrefix: "as-needed",
});
`;
}

function requestTs(): string {
  return `// Generated by parrot — next-intl request config. Loads the per-request locale's messages.
import { getRequestConfig } from "next-intl/server";
import { routing } from "./routing";

export default getRequestConfig(async ({ requestLocale }) => {
  // requestLocale is a Promise on Next 15+ — await it (P3).
  const requested = await requestLocale;
  const locale = routing.locales.includes(requested as (typeof routing.locales)[number])
    ? (requested as string)
    : routing.defaultLocale;

  return {
    locale,
    messages: (await import(\`../../messages/\${locale}.json\`)).default,
  };
});
`;
}

function middlewareTs(): string {
  // Same body whether the file is named proxy.ts (Next 16) or middleware.ts (<16) — the rename is the trap.
  return `// Generated by parrot — next-intl locale routing (createMiddleware).
// NOTE: on Next.js 16+ this file MUST be named \`proxy.ts\` (the framework renamed middleware.ts → proxy.ts);
// a middleware.ts on Next 16 is SILENTLY ignored (P2/S2). parrot picked this filename by version detection.
import createMiddleware from "next-intl/middleware";
import { routing } from "./i18n/routing";

export default createMiddleware(routing);

export const config = {
  // Match all pathnames except for API, Next internals, and files with an extension.
  matcher: ["/((?!api|_next|_vercel|.*\\\\..*).*)"],
};
`;
}

function localeLayoutTsx(): string {
  return `// Generated by parrot — the [locale] root layout. Carries the 3 setup footguns dodged by construction:
//   - await params (P3)            - setRequestLocale in every static page/layout (P1/S1)
//   - <html lang dir> for RTL (O24/P28)
import { NextIntlClientProvider } from "next-intl";
import { getMessages, setRequestLocale } from "next-intl/server";
import { notFound } from "next/navigation";
import { routing } from "../../i18n/routing";

// RTL scripts — set <html dir="rtl"> so Arabic/Hebrew/etc. render correctly (not LTR). S7/O11.
const RTL_LOCALES = new Set(["ar", "he", "fa", "ur", "ps", "dv", "yi"]);

export function generateStaticParams() {
  return routing.locales.map((locale) => ({ locale }));
}

export default async function LocaleLayout({
  children,
  params,
}: {
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}) {
  const { locale } = await params; // P3: params is a Promise on Next 15+
  if (!routing.locales.includes(locale as (typeof routing.locales)[number])) notFound();

  // P1/S1: enable static rendering for this locale — WITHOUT this, the page renders defaultLocale silently.
  setRequestLocale(locale);

  const messages = await getMessages();
  const dir = RTL_LOCALES.has(locale.split("-")[0] ?? locale) ? "rtl" : "ltr";

  return (
    <html lang={locale} dir={dir}>
      <body>
        <NextIntlClientProvider messages={messages}>{children}</NextIntlClientProvider>
      </body>
    </html>
  );
}
`;
}

function seedPageTsx(): string {
  return `// Generated by parrot — a seed [locale] page demonstrating the correct pattern. Safe to replace.
import { setRequestLocale } from "next-intl/server";
import { useTranslations } from "next-intl";

export default async function HomePage({ params }: { params: Promise<{ locale: string }> }) {
  const { locale } = await params; // P3
  setRequestLocale(locale); // P1/S1 — required in EVERY static page, not just the layout

  return <Welcome />;
}

function Welcome() {
  const t = useTranslations("home");
  // Full-sentence ICU via the catalog (never concatenate fragments — P9/O8).
  return <h1>{t("title")}</h1>;
}
`;
}

function seedMessages(locale: string): string {
  // A correct full-sentence message + a plural authored for the locale's categories (the right pattern).
  return `${JSON.stringify({ home: { title: locale === "en" ? "Welcome" : `Welcome (${locale})` } }, null, 2)}\n`;
}

/**
 * Wire next-intl into `appDir`. Idempotent: only writes files that don't exist. Returns what was written vs
 * skipped + the version-detected middleware filename.
 */
export function runInit(appDir: string, lib: I18nLib, locales: string[], defaultLocale: string): InitResult {
  const written: string[] = [];
  const skipped: string[] = [];

  mkdirSync(appDir, { recursive: true });
  const nextMajor = detectNextMajor(appDir);
  // Version-detected routing file: proxy.ts on Next 16+, middleware.ts before. Unknown → assume current (16).
  const useProxy = nextMajor === null || nextMajor >= 16;
  const middlewareRel = useProxy ? "src/proxy.ts" : "src/middleware.ts";

  if (lib === "next-intl") {
    writeIfAbsent(appDir, "src/i18n/routing.ts", routingTs(locales, defaultLocale), written, skipped);
    writeIfAbsent(appDir, "src/i18n/request.ts", requestTs(), written, skipped);
    writeIfAbsent(appDir, middlewareRel, middlewareTs(), written, skipped);
    writeIfAbsent(appDir, "src/app/[locale]/layout.tsx", localeLayoutTsx(), written, skipped);
    writeIfAbsent(appDir, "src/app/[locale]/page.tsx", seedPageTsx(), written, skipped);
    for (const loc of locales) {
      writeIfAbsent(appDir, `messages/${loc}.json`, seedMessages(loc), written, skipped);
    }
  } else {
    // i18next path is documented but not codegen'd in C1 — the acceptance + default is next-intl (Q3/O4).
    throw new Error(
      "parrot init --lib i18next is not yet codegen'd; the wired default is next-intl (Q3/O4). " +
        "Use --lib next-intl, or see skills/i18n-setup-nextjs for the i18next pattern.",
    );
  }

  return {
    dir: appDir,
    lib,
    nextVersion: nextMajor,
    middlewareFile: middlewareRel,
    filesWritten: written,
    filesSkipped: skipped,
    defaultLocale,
    locales,
  };
}
